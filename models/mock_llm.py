"""
models/mock_llm.py
──────────────────
Data-driven MockLLM for demo / offline mode.

Rather than returning static canned text, this mock:
  1. Parses the incoming prompt to identify the task type.
  2. Loads the relevant sample JSON via utils/data_loader.
  3. Computes real statistics from the data.
  4. Composes a structured, multi-paragraph response that references
     actual data values — making demo mode feel like genuine AI analysis.

Implements the LangChain BaseLLM interface so it is a drop-in replacement
for WatsonxLLM throughout the application.
"""

from __future__ import annotations

import logging
import textwrap
from typing import Any, List, Optional

logger = logging.getLogger(__name__)

# ── LangChain base class ──────────────────────────────────────────────────────
try:
    from langchain_core.language_models.llms import LLM
except ImportError:
    from langchain.llms.base import LLM  # type: ignore[no-redef]


class MockLLM(LLM):
    """
    Offline, data-driven LLM for demo mode.

    All responses are generated by inspecting the bundled sample data files
    and formatting real statistics into readable market-research prose.
    """

    # LangChain requires these fields to be declared as class-level annotations
    # when using Pydantic v2 (which newer LangChain versions use).
    class Config:
        arbitrary_types_allowed = True

    @property
    def _llm_type(self) -> str:
        return "mock"

    def _call(
        self,
        prompt: str,
        stop: Optional[List[str]] = None,
        run_manager: Optional[Any] = None,
        **kwargs: Any,
    ) -> str:
        """Route prompt to the appropriate response builder based on task type."""
        pl = prompt.lower()

        if any(w in pl for w in ["sentiment", "review", "customer feedback", "opinion"]):
            return self._build_sentiment_response()
        if any(w in pl for w in ["competitor", "comparison", "market share", "rival"]):
            return self._build_competitor_response()
        if any(w in pl for w in ["trend", "keyword", "search volume", "growing"]):
            return self._build_trend_response()
        if any(w in pl for w in ["demand", "demand index", "demand forecast", "demand indicator"]):
            return self._build_demand_response()
        if any(w in pl for w in ["full report", "generate report", "market report", "research report"]):
            return self._build_report_response()
        if any(w in pl for w in ["news", "article", "headline", "recent development"]):
            return self._build_news_response()
        if any(w in pl for w in ["document", "retrieved", "context", "according to", "based on"]):
            return self._build_rag_response(prompt)
        return self._build_generic_response()

    # ── Response builders ─────────────────────────────────────────────────────

    def _build_sentiment_response(self) -> str:
        from utils.data_loader import load_reviews, get_sentiment_summary
        reviews = load_reviews()
        ss = get_sentiment_summary()
        if not ss:
            return "Insufficient review data available for sentiment analysis."

        # Top positive and negative review samples
        positives = [r for r in reviews if r.get("sentiment") == "positive"][:3]
        negatives = [r for r in reviews if r.get("sentiment") == "negative"][:2]

        pos_excerpts = "\n".join(
            f'  • ({r["product"]}, ★{r["rating"]}) "{r["review_text"][:120]}..."'
            for r in positives
        )
        neg_excerpts = "\n".join(
            f'  • ({r["product"]}, ★{r["rating"]}) "{r["review_text"][:120]}..."'
            for r in negatives
        )

        # Product-level breakdown
        from collections import defaultdict
        prod_ratings: dict[str, list[int]] = defaultdict(list)
        for r in reviews:
            prod_ratings[r["product"]].append(r["rating"])
        prod_avg = {p: round(sum(v)/len(v), 2) for p, v in prod_ratings.items()}
        top_product = max(prod_avg, key=lambda p: prod_avg[p])
        low_product = min(prod_avg, key=lambda p: prod_avg[p])

        return textwrap.dedent(f"""
        ## 🤖 AI Analysis — Customer Sentiment Report

        **Overview**
        Analysis of {ss['total_reviews']} customer reviews reveals an overall **positive market sentiment**,
        with {ss['positive_pct']}% of reviews classified as positive, {ss['neutral_pct']}% neutral, and
        {ss['negative_pct']}% negative. The mean star rating across all products is **{ss['avg_rating']}/5.0**.

        **Product-Level Highlights**
        - Highest-rated product: **{top_product}** (avg {prod_avg[top_product]}/5.0)
        - Lowest-rated product: **{low_product}** (avg {prod_avg[low_product]}/5.0)

        **Representative Positive Feedback**
        Customers consistently praise enterprise reliability, developer experience, and AI model quality:
{pos_excerpts}

        **Representative Negative Feedback**
        Key pain points include customer support responsiveness, pricing transparency, and product innovation pace:
{neg_excerpts}

        **Key Themes Identified**
        1. *Developer experience* is the top differentiator for mid-market customers.
        2. *Pricing transparency* is the most common source of negative reviews.
        3. *Support responsiveness* and *AI capability depth* are critical for enterprise renewal decisions.
        4. Customers in regulated industries (banking, healthcare) prioritise compliance features over price.

        **Sentiment Trend**
        Reviews from Q3/Q4 2024 show improving sentiment for cloud-native providers and declining sentiment
        for legacy incumbents — reflecting the broader market shift toward modern, AI-first platforms.

        > 🔮 *Forecast / Interpretation:* If support and pricing transparency issues remain unresolved,
        > the negative review share is likely to grow. Providers that invest in self-service tooling and
        > clearer billing are projected to see 8–12% improvement in NPS scores over the next two quarters.
        > This is an analytical projection, not a guaranteed outcome.
        """).strip()

